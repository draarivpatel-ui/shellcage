/*
 * Generate the CommonJS build from the single ESM source of truth.
 * The transform is intentionally small, deterministic and auditable.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');
const checkMode = process.argv.includes('--check');

const EXPORT_NAMES = [
  'SHELLCAGE_VERSION', 'CODES', 'DEFAULT_ALLOWED_ENV', 'ShellCageError',
  'assertSafeArg', 'safeArg', 'safePathArg', 'buildArgv',
  'validateInvocation', 'auditArgv', 'sanitizeEnv', 'auditEnv',
  'safeSpawn', 'safeExecFile', 'createShellCage'
];

let body = source;
const childProcessImport = "import { spawn } from 'node:child_process';";
const fsImport = "import fs from 'node:fs';";
const pathImport = "import path from 'node:path';";
if (!body.includes(childProcessImport)) throw new Error('CJS transform could not find the node:child_process import');
if (!body.includes(fsImport)) throw new Error('CJS transform could not find the node:fs import');
if (!body.includes(pathImport)) throw new Error('CJS transform could not find the node:path import');
body = body.replace(childProcessImport, "const { spawn } = require('node:child_process');");
body = body.replace(fsImport, "const fs = require('node:fs');");
body = body.replace(pathImport, "const path = require('node:path');");
body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');
if (!body.includes('export default shellcage;')) throw new Error('CJS transform could not find the default export');
body = body.replace('export default shellcage;', '');
if (/^export\s/m.test(body)) throw new Error('CJS transform left an export declaration behind');
if (/^import\s/m.test(body)) throw new Error('CJS transform left an import declaration behind');
for (const name of EXPORT_NAMES) {
  const declaration = new RegExp('(?:const|class|function) ' + name + '\\b');
  if (!declaration.test(body)) throw new Error('CJS transform could not find declaration for ' + name);
}

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body.trim(),
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

const target = path.join(root, 'dist', 'index.cjs');
if (checkMode) {
  let existing = '';
  try {
    existing = await readFile(target, 'utf8');
  } catch {
    existing = '';
  }
  if (existing !== output) {
    throw new Error('dist/index.cjs is not up to date; run node scripts/build-cjs.mjs');
  }
  process.stdout.write('dist/index.cjs is up to date\n');
} else {
  await mkdir(path.join(root, 'dist'), { recursive: true });
  await writeFile(target, output, 'utf8');
  process.stdout.write('dist/index.cjs generated from src/index.mjs\n');
}
